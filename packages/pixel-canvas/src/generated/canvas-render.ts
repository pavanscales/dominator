import { effect } from '@dominator/core';
import * as stateModule from '../state';

export const render = () => {
  const state = stateModule;
  const { active, currentColor, draw, erase, exportToPNG, historyLength, redo, redoLength, tool, undo } = state;

  const v1 = document.createElement("div");
  v1.setAttribute("class", "pixel-canvas-app");
  const v2 = document.createElement("header");
  const v3 = document.createElement("h1");
  const v4 = document.createTextNode("Dominator Pixel");
  v3.appendChild(v4);
  v2.appendChild(v3);
  const v5 = document.createElement("div");
  v5.setAttribute("class", "tools");
  const v6 = document.createElement("div");
  v6.setAttribute("class", "tool-group");
  const v7 = document.createElement("label");
  const v8 = document.createTextNode("Color");
  v7.appendChild(v8);
  v6.appendChild(v7);
  const v9 = document.createElement("input");
  v9.setAttribute("type", "color");
  effect(() => { v9.setAttribute("value", currentColor()); });
  v9.addEventListener("input", e => currentColor.set(e.target.value));
  v9.setAttribute("title", "Pick Color");
  v6.appendChild(v9);
  v5.appendChild(v6);
  const v10 = document.createElement("div");
  v10.setAttribute("class", "tool-group");
  const v11 = document.createElement("button");
  v11.addEventListener("click", () => tool.set('draw'));
  effect(() => { v11.setAttribute("class", tool() === 'draw' ? 'active' : ''); });
  const v12 = document.createTextNode("Draw");
  v11.appendChild(v12);
  v10.appendChild(v11);
  const v13 = document.createElement("button");
  v13.addEventListener("click", () => tool.set('erase'));
  effect(() => { v13.setAttribute("class", tool() === 'erase' ? 'active' : ''); });
  const v14 = document.createTextNode("Erase");
  v13.appendChild(v14);
  v10.appendChild(v13);
  v5.appendChild(v10);
  const v15 = document.createElement("div");
  v15.setAttribute("class", "tool-group");
  const v16 = document.createElement("button");
  v16.addEventListener("click", undo);
  effect(() => { v16.setAttribute("disabled", historyLength() === 0); });
  v16.setAttribute("title", "Undo (Ctrl+Z)");
  const v17 = document.createTextNode("Undo");
  v16.appendChild(v17);
  v15.appendChild(v16);
  const v18 = document.createElement("button");
  v18.addEventListener("click", redo);
  effect(() => { v18.setAttribute("disabled", redoLength() === 0); });
  v18.setAttribute("title", "Redo (Ctrl+Y)");
  const v19 = document.createTextNode("Redo");
  v18.appendChild(v19);
  v15.appendChild(v18);
  v5.appendChild(v15);
  v2.appendChild(v5);
  v1.appendChild(v2);
  const v20 = document.createElement("main");
  const v21 = document.createElement("div");
  v21.setAttribute("class", "grid-container");
  const v22 = document.createElement("div");
  v22.setAttribute("class", "grid");
  v21.appendChild(v22);
  v20.appendChild(v21);
  const v23 = document.createElement("aside");
  v23.setAttribute("class", "sidebar");
  const v24 = document.createElement("section");
  v24.setAttribute("class", "stats-section");
  const v25 = document.createElement("h3");
  const v26 = document.createTextNode("History &amp; Stats");
  v25.appendChild(v26);
  v24.appendChild(v25);
  const v27 = document.createElement("h3");
  const v28 = document.createTextNode("Palette Usage");
  v27.appendChild(v28);
  v24.appendChild(v27);
  v23.appendChild(v24);
  const v29 = document.createElement("div");
  v29.setAttribute("class", "sidebar-footer");
  const v30 = document.createElement("button");
  v30.setAttribute("class", "export-btn");
  v30.addEventListener("click", exportToPNG);
  const v31 = document.createTextNode("Export Artifact");
  v30.appendChild(v31);
  v29.appendChild(v30);
  v23.appendChild(v29);
  v20.appendChild(v23);
  v1.appendChild(v20);
  return v1;
};